def auto_members(spec: Spec) -> List[tuple]:
    members = []
    for eq in spec.controlled():
        for suffix, datatype, comment in AUTO_MEMBERS.get(eq.type, []):
            members.append((f"{eq.name}{suffix}", datatype, f"{eq.name}: {comment}"))
    return members


def alarm_members(spec: Spec) -> List[tuple]:
    members: List[tuple] = [("SafetyOpen", "Bool", "safety circuit open (status only)")]
    for eq in spec.controlled():
        roles = eq.typedef.alarm_roles
        if "fault" in roles:
            label = "signal fault / out of range" if eq.type == "analog_input" else "device fault"
            members.append((f"{eq.name}_Fault", "Bool", f"{eq.name}: {label}"))
        if "limits" in roles and _uses_limits(eq):
            sc = eq.scaling
            if sc.get("lo_lo") is not None:
                members.append((f"{eq.name}_LoLo", "Bool", f"{eq.name}: below {sc['lo_lo']} {sc['unit']}"))
            if sc.get("lo") is not None:
                members.append((f"{eq.name}_Lo", "Bool", f"{eq.name}: below {sc['lo']} {sc['unit']}"))
            if sc.get("hi") is not None:
                members.append((f"{eq.name}_Hi", "Bool", f"{eq.name}: above {sc['hi']} {sc['unit']}"))
            if sc.get("hi_hi") is not None:
                members.append((f"{eq.name}_HiHi", "Bool", f"{eq.name}: above {sc['hi_hi']} {sc['unit']}"))
    return members


def cmd_members(spec: Spec) -> List[tuple]:
    return [
        ("Start", "Bool", "momentary: start the auto sequence"),
        ("Stop", "Bool", "momentary: stop the auto sequence"),
        ("Reset", "Bool", "momentary: acknowledge all faults"),
        ("ReqManual", "Bool", "momentary: select manual mode"),
        ("ReqAuto", "Bool", "momentary: select auto mode"),
    ]


def _uses_limits(eq: Equipment) -> bool:
    return any(eq.scaling.get(k) is not None for k in ("lo_lo", "lo", "hi", "hi_hi"))


def emit_udt_auto(spec: Spec) -> str:
    return _struct(
        spec.udt_auto,
        auto_members(spec),
        "Auto-mode requests. The AUTO SEQUENCE region of the machine FB writes these;\n"
        "the device FBs read them. Nothing else should write to this struct.",
    )


def emit_udt_alarms(spec: Spec) -> str:
    return _struct(
        spec.udt_alarms,
        alarm_members(spec),
        "One bit per alarm condition, refreshed every cycle by the machine FB.\n"
        "Bind HMI alarms to <instance DB>.Alarms.<member>.",
    )


def emit_udt_cmd(spec: Spec) -> str:
    return _struct(
        spec.udt_cmd,
        cmd_members(spec),
        "Machine-level HMI commands. All members are momentary: the machine FB\n"
        "evaluates and clears them in the same cycle.",
    )



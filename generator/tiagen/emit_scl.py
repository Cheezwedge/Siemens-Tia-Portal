"""Emitters for the machine-specific SCL: interface UDTs, the machine FB and OB1."""

from __future__ import annotations

from typing import Dict, List

from . import devices as dev
from .model import Equipment, Spec

HEADER = "// Generated by tiagen - edit the machine spec, not this file.\n"

# Auto-mode request members contributed by each equipment type.
AUTO_MEMBERS = {
    "motor_dol": [("_Start", "Bool", "auto start request"), ("_Stop", "Bool", "auto stop request")],
    "motor_reversing": [("_Fwd", "Bool", "auto forward request"), ("_Rev", "Bool", "auto reverse request")],
    "vfd_analog": [
        ("_Start", "Bool", "auto start request"),
        ("_Stop", "Bool", "auto stop request"),
        ("_Speed", "Real", "auto speed setpoint"),
    ],
    "valve_single": [("_Open", "Bool", "auto open request")],
    "valve_double": [("_Open", "Bool", "auto open request")],
    "digital_output": [("_Cmd", "Bool", "auto command")],
    "analog_output": [("_Value", "Real", "auto setpoint")],
}


def _q(name: str) -> str:
    return f'"{name}"'


def _struct(type_name: str, members: List[tuple], doc: str = "") -> str:
    """Render a TYPE ... END_TYPE block. `members` is a list of (name, datatype, comment)."""
    width = max((len(m[0]) for m in members), default=1)
    lines = [HEADER, f"TYPE {_q(type_name)}", "VERSION : 0.1", "   STRUCT"]
    if not members:
        # An empty STRUCT is not valid SCL; keep a documented placeholder member.
        lines.append("      Reserved : Bool;   // no members required by this spec")
    for name, datatype, comment in members:
        pad = " " * (width - len(name))
        suffix = f"   // {comment}" if comment else ""
        lines.append(f"      {name}{pad} : {datatype};{suffix}")
    lines += ["   END_STRUCT;", "", "END_TYPE"]
    if doc:
        lines += ["", "(*", doc.rstrip(), "*)"]
    return "\n".join(lines) + "\n"



def emit_ob_main(spec: Spec) -> str:
    return (
        HEADER
        + f"ORGANIZATION_BLOCK {_q(spec.ob_main)}\n"
        "TITLE = 'Program cycle'\n"
        "{ S7_Optimized_Access := 'TRUE' }\n"
        "VERSION : 0.1\n"
        "BEGIN\n"
        f"    {_q(spec.db_machine)}();\n"
        "END_ORGANIZATION_BLOCK\n"
        "\n"
        "(*\n"
        f"   Calls the machine FB through its instance DB {spec.db_machine}.\n"
        "\n"
        "   The build plan deletes the project's default Main [OB1] before importing\n"
        "   this one, so that OB1 ends up as this SCL block. If your TIA version\n"
        "   refuses the import, keep the original Main [OB1] and add the single line\n"
        f"   {spec.db_machine}(); to it by hand - that is the only manual code step.\n"
        "*)\n"
    )

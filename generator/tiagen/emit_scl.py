def _safety_expression(spec: Spec) -> str:
    inputs = spec.safety_inputs()
    if not inputs:
        return "TRUE"
    terms = []
    for eq in inputs:
        sig = eq.signal("ok_fb")
        terms.append(_q(sig.tag))
    return "\n                    AND ".join(terms)


def _interlock_expression(eq: Equipment) -> str:
    others = eq.options.get("interlock_from") or []
    if not others:
        return "TRUE"
    return " AND ".join(f"#{o}.Hmi.Sts_Running" for o in others)


def _device_call(spec: Spec, eq: Equipment) -> str:
    ctx: Dict = {
        "enable": "#vEnable",
        "manual": "#vManual",
        "reset": "#vReset",
        "auto": "#Auto.",
        "interlock": _interlock_expression(eq),
        "tag": lambda role: _q(eq.signal(role).tag),
        "has": eq.has,
    }
    params = eq.typedef.call(eq, ctx)
    indent = " " * (len(eq.name) + 6)
    body = (",\n" + indent).join(params)
    head = f"    #{eq.name}({body});"
    label = eq.description or eq.typedef.summary
    return f"    // {eq.name}: {label}\n{head}"


def emit_fb_machine(spec: Spec) -> str:
    controlled = spec.controlled()
    lines: List[str] = [HEADER, f"FUNCTION_BLOCK {_q(spec.fb_machine)}"]
    lines.append("{ S7_Optimized_Access := 'TRUE' }")
    lines.append("VERSION : 0.1")

    # ---- interface -------------------------------------------------------
    lines += [
        "   VAR_OUTPUT",
        "      State : Int;                       // see FB_ModeManager states",
        "      AutoRun : Bool;                    // auto sequence is allowed to advance",
        "      AnyFault : Bool;                   // at least one alarm is active",
        "   END_VAR",
        "",
        "   VAR",
        f"      Mode : {_q('FB_ModeManager')};",
        f"      Cmd : {_q(spec.udt_cmd)};              // HMI machine commands",
        f"      Auto : {_q(spec.udt_auto)};            // auto-mode requests",
        f"      Alarms : {_q(spec.udt_alarms)};        // alarm bits for the HMI",
        "      DevicesHealthy : Bool := TRUE;     // aggregated at the end of each cycle",
    ]
    if spec.sequence:
        lines += [
            f"      Cond : {_q(spec.udt_cond)};            // resolved step conditions",
            f"      Seq : {_q(spec.fb_sequence)};          // the generated step sequence",
        ]
    if controlled:
        lines.append("      // ---- device instances ----")
        width = max(len(e.name) for e in controlled)
        for eq in controlled:
            pad = " " * (width - len(eq.name))
            lines.append(f"      {eq.name}{pad} : {_q(eq.typedef.fb)};")
    lines += [
        "   END_VAR",
        "",
        "   VAR_TEMP",
        "      vSafetyOk : Bool;",
        "      vEnable : Bool;",
        "      vManual : Bool;",
        "      vReset : Bool;",
        "   END_VAR",
        "",
        "BEGIN",
    ]

    # ---- 1. safety status ------------------------------------------------
    lines += [
        "    // ==================================================================",
        "    // 1. Safety STATUS aggregation.",
        "    //    These contacts tell the standard program what the safety system",
        "    //    is doing. They do not implement the safety function itself.",
        "    // ==================================================================",
        f"    #vSafetyOk := {_safety_expression(spec)};",
        "",
    ]

    # ---- 2. mode manager -------------------------------------------------
    start_eq = spec.by_control_role("start")
    stop_eq = spec.by_control_role("stop")
    reset_eq = spec.by_control_role("reset")

    start_expr = "#Cmd.Start"
    if start_eq:
        start_expr = f"#Cmd.Start OR {_q(start_eq.signal('in').tag)}"
    stop_expr = "TRUE"
    if stop_eq:
        stop_expr = _q(stop_eq.signal("in").tag)
    reset_expr = "#Cmd.Reset"
    if reset_eq:
        reset_expr = f"#Cmd.Reset OR {_q(reset_eq.signal('in').tag)}"

    lines += [
        "    // ==================================================================",
        "    // 2. Mode manager. Owns Enable, the manual/auto selection and reset.",
        "    // ==================================================================",
        "    #Mode(SafetyOk := #vSafetyOk,",
        "          DevicesHealthy := #DevicesHealthy,",
        "          ReqManual := #Cmd.ReqManual,",
        "          ReqAuto := #Cmd.ReqAuto,",
        f"          StartCmd := {start_expr},",
        "          StopCmd := #Cmd.Stop,",
        f"          StopOk := {stop_expr},",
        f"          ResetCmd := {reset_expr},",
    ]
    if spec.sequence:
        # The sequencer runs later in this cycle, so this is last cycle's pulse.
        # One cycle late to leave auto is harmless, and it avoids reordering the
        # mode manager behind the sequence it gates.
        lines.append("          CycleComplete := #Seq.Complete);")
    else:
        lines.append("          CycleComplete := FALSE);")
    lines += [
        "",
        "    // Momentary HMI commands are consumed once the mode manager has seen them.",
        "    #Cmd.Start := FALSE;",
        "    #Cmd.Stop := FALSE;",
        "    #Cmd.Reset := FALSE;",
        "    #Cmd.ReqManual := FALSE;",
        "    #Cmd.ReqAuto := FALSE;",
        "",
        "    #vEnable := #Mode.Enable;",
        "    #vManual := #Mode.ManualMode;",
        "    #vReset := #Mode.GroupReset;",
        "    #State := #Mode.State;",
        "    #AutoRun := #Mode.AutoRun;",
        "",
    ]

    # ---- 3. auto sequence region ----------------------------------------
    if spec.sequence:
        lines += [
            "    // ==================================================================",
            "    // 3. AUTO SEQUENCE - generated from the spec's sequence section.",
            "    //",
            "    //    The step logic lives in its own FB. Edit the spec and rebuild;",
            "    //    the hand-written region below is for anything the step table",
            "    //    cannot express, and runs after the sequencer each cycle.",
            "    // ==================================================================",
            "    IF NOT #AutoRun THEN",
        ]
    else:
        lines += [
            "    // ==================================================================",
            "    // 3. AUTO SEQUENCE - machine specific, written by hand.",
            "    //",
            "    //    Everything above and below this region is generated. Write the",
            "    //    sequence here by setting members of #Auto, gated on #AutoRun.",
            "    //    Regenerating the project preserves nothing inside this region,",
            "    //    so keep the sequence in its own block once it grows: create an",
            "    //    FB, add it to the spec as a library block and call it from here.",
            "    // ==================================================================",
            "    IF NOT #AutoRun THEN",
        ]
    lines += [
        "        // Auto is not running: drop every auto request so manual mode is clean.",
    ]
    for name, datatype, _ in auto_members(spec):
        default = "0.0" if datatype == "Real" else "FALSE"
        lines.append(f"        #Auto.{name} := {default};")
    if not auto_members(spec):
        lines.append("        ;   // no auto requests in this spec")
    lines += ["    END_IF;", ""]
    if spec.sequence:
        from . import emit_seq
        lines += emit_seq.machine_call(spec, spec.sequence)
        lines += [
            "    // >>> BEGIN AUTO SEQUENCE >>>",
            "    // The step table above owns the sequence. Use this region only for",
            "    // what a step table cannot say - it runs after the sequencer, so an",
            "    // assignment here overrides the active step's request.",
            "    ;",
            "    // <<< END AUTO SEQUENCE <<<",
            "",
        ]
    else:
        lines += ["    // >>> BEGIN AUTO SEQUENCE >>>"]
        lines += _sequence_hint(spec)
        lines += ["    // <<< END AUTO SEQUENCE <<<", ""]

    # ---- 4. device calls -------------------------------------------------
    lines += [
        "    // ==================================================================",
        "    // 4. Device calls. One call per piece of equipment in the spec.",
        "    // ==================================================================",
    ]
    if controlled:
        for eq in controlled:
            lines.append(_device_call(spec, eq))
            lines.append("")
    else:
        lines += ["    ;   // no controlled equipment in this spec", ""]

    # ---- 5. alarms -------------------------------------------------------
    lines += [
        "    // ==================================================================",
        "    // 5. Alarm bits and health aggregation.",
        "    // ==================================================================",
        "    #Alarms.SafetyOpen := NOT #vSafetyOk;",
    ]
    fault_terms: List[str] = ["#Alarms.SafetyOpen"]
    for eq in spec.controlled():
        roles = eq.typedef.alarm_roles
        if "fault" in roles:
            lines.append(f"    #Alarms.{eq.name}_Fault := #{eq.name}.Fault;")
            fault_terms.append(f"#Alarms.{eq.name}_Fault")
        if "limits" in roles and _uses_limits(eq):
            sc = eq.scaling
            if sc.get("lo_lo") is not None:
                lines.append(f"    #Alarms.{eq.name}_LoLo := #{eq.name}.AlmLoLo;")
                fault_terms.append(f"#Alarms.{eq.name}_LoLo")
            if sc.get("lo") is not None:
                lines.append(f"    #Alarms.{eq.name}_Lo := #{eq.name}.AlmLo;")
            if sc.get("hi") is not None:
                lines.append(f"    #Alarms.{eq.name}_Hi := #{eq.name}.AlmHi;")
            if sc.get("hi_hi") is not None:
                lines.append(f"    #Alarms.{eq.name}_HiHi := #{eq.name}.AlmHiHi;")
                fault_terms.append(f"#Alarms.{eq.name}_HiHi")

    lines.append("")
    lines.append("    // Only latching / trip-level conditions block the machine.")
    if len(fault_terms) == 1:
        lines.append(f"    #AnyFault := {fault_terms[0]};")
    else:
        joined = "\n                ".join(
            [fault_terms[0]] + [f"OR {t}" for t in fault_terms[1:]]
        )
        lines.append(f"    #AnyFault := {joined};")
    lines += [
        "    #DevicesHealthy := NOT #AnyFault;",
        "END_FUNCTION_BLOCK",
    ]
    return "\n".join(lines) + "\n"


def _sequence_hint(spec: Spec) -> List[str]:
    """A commented, spec-specific example of the sequence idiom."""
    motors = [e for e in spec.controlled() if e.type in ("motor_dol", "motor_reversing", "vfd_analog")]
    valves = [e for e in spec.controlled() if e.type in ("valve_single", "valve_double")]
    sensors = [e for e in spec.equipment if e.type == "digital_input"
               and not e.options.get("control_role")]

    if not motors:
        return ["", "    // Write the auto-mode logic here, gated on #AutoRun.", ""]

    motor = motors[0]
    lines = [
        "",
        "    // The idiom: gate everything on #AutoRun and write only to #Auto members.",
        "    // Device FBs own the outputs - never write a %Q tag from here.",
        "    //",
        "    // IF #AutoRun THEN",
        f"    //     #Auto.{motor.name}_Start := TRUE;",
    ]
    if valves:
        condition = f"#{motor.name}.Hmi.Sts_Running"
        if sensors:
            condition = f'"{sensors[0].name}" AND {condition}'
        lines.append(f"    //     #Auto.{valves[0].name}_Open := {condition};")
    if motor.type == "vfd_analog":
        lines.append(f"    //     #Auto.{motor.name}_Speed := 35.0;")
    lines += [
        "    // ELSE",
        f"    //     #Auto.{motor.name}_Stop := TRUE;",
        "    // END_IF;",
        "",
    ]
    return lines



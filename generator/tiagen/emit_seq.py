# HMI text lists
# --------------------------------------------------------------------------
def text_lists(spec: Spec, seq: Sequence) -> List[dict]:
    """Step messages and blocked reasons, as text lists.

    A Unified Basic panel has no scripting, so a message cannot be assembled at
    runtime. Both lists are therefore indexed by a value the PLC publishes, and a
    symbolic I/O field resolves the text - configuration only, no script.
    """
    steps = [
        {"value": seq.idle_number, "text": "Idle - auto not running"},
    ] + [
        {"value": s.number, "text": s.message} for s in seq.steps
    ]

    reasons = [{"value": 0, "text": "Not waiting"}]
    for index, cond in enumerate(seq_mod.reasons_of(spec, seq), start=1):
        reasons.append({"value": index, "text": _reason_text(spec, cond)})

    return [
        {
            "name": f"{seq.name}_StepMessage",
            "selection": "value",
            "tag": f"{spec.db_machine}.Seq.Step",
            "comment": "Step message, indexed by the active step number",
            "entries": steps,
        },
        {
            "name": f"{seq.name}_BlockedBy",
            "selection": "value",
            "tag": f"{spec.db_machine}.Seq.BlockedById",
            "comment": "Why the active step is not advancing",
            "entries": reasons,
        },
    ]


def _reason_text(spec: Spec, cond) -> str:
    """Phrase a condition as the thing the machine is waiting for.

    A negated condition is phrased "to clear" rather than printed with a NOT: the
    person reading this is looking at a 7-inch panel, not a listing.
    """
    words = cond.source.strip().split()
    subject = words[1] if words[0].lower() == "not" else words[0]
    device_name = subject.split(".")[0]

    description = None
    for eq in spec.equipment:
        if eq.name == device_name:
            description = eq.description
            break

    what = subject if not cond.negated else subject
    phrase = f"Waiting for {what} to clear" if cond.negated else f"Waiting for {what}"
    if len(words) == 3:      # a comparison: keep the operator and the number
        phrase = f"Waiting for {' '.join(words[-3:])}"
    return f"{phrase} ({description})" if description else phrase

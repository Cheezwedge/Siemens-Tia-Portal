# The machine FB's half: fill Cond, call the sequencer
# --------------------------------------------------------------------------
def machine_call(spec: Spec, seq: Sequence) -> List[str]:
    """Lines the machine FB uses to evaluate conditions and run the sequencer."""
    conditions = seq_mod.conditions_of(spec, seq)
    lines = [
        "    // ==================================================================",
        "    // 3a. Step conditions. Every condition the sequence waits on, read",
        "    //     from the device instances. This is the only place a status",
        "    //     name in the spec becomes a DevIf member.",
        "    // ==================================================================",
    ]
    width = max((len(c.key) for c in conditions), default=1)
    for cond in conditions:
        pad = " " * (width - len(cond.key))
        lines.append(f"    #Cond.{cond.key}{pad} := {cond.expression};")
    if not conditions:
        lines.append("    ;   // the sequence waits on nothing")
    lines += [
        "",
        "    // ==================================================================",
        "    // 3b. The generated step sequence.",
        "    // ==================================================================",
        "    // Hold reads last cycle's fault state, because alarms are aggregated in",
        "    // section 5. One cycle late to stop advancing is harmless - the device FBs",
        "    // have already dropped their outputs via Enable. AnyFault already includes",
        "    // the safety status, so it is the only term needed here.",
        "    #Seq(AutoRun := #AutoRun,",
        "         Reset := #vReset,",
        "         Hold := #AnyFault,",
        "         Cond := #Cond,",
        "         Auto := #Auto);",
        "",
    ]
    return lines


